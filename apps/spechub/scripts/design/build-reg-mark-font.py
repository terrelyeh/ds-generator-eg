"""
Build the one-glyph font that prints ® as a superscript in datasheet body copy.

    uv run --no-project --with fonttools --with brotli \
        python apps/spechub/scripts/design/build-reg-mark-font.py

Roboto draws ® as a full-size circle sitting on the baseline (as tall as a
capital H), so "Intel® Atom®" in a spec table reads as two stray letters.
Manrope — the heading face — already draws it small and raised, which is
why only the body copy looked wrong.

Wrapping every ® in <sup> would mean touching every text node in five
layouts, and a <sup> nudges the line box. Instead this script takes
Roboto's own ® glyph, shrinks it and lifts it to cap height, and writes it
as a font that covers U+00AE only. Each layout puts that font first in its
body stack (`withRegMark()` in lib/datasheet/typography.ts): the browser
uses it for ® and falls through to Roboto (or the locale's face) for every
other character. Line height is unchanged — the glyph stays inside
Roboto's ascent — and the glyph gets narrower, so the pagination estimates
in lib/datasheet/ only become slightly more conservative.

Output: src/lib/datasheet/reg-mark-font.ts (generated — don't hand-edit;
change SCALE and re-run).
"""

import base64
import io
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "roboto-latin.woff2"
OUT = HERE.parent.parent / "src/lib/datasheet/reg-mark-font.ts"

FAMILY = "EG Reg Mark"
# Height of the mark relative to Roboto's own ®. 0.55 makes the circle
# ~57% of cap height — between Roboto's ™ (37%) and Manrope's ® (65%).
SCALE = 0.55
# Side bearing kept on each side of the scaled glyph, in font units.
GAP = 40

src = TTFont(SOURCE)
if "fvar" in src:
    # Regular (400) — the mark is too small for the weight to show, and one
    # static glyph keeps the file at ~1 KB.
    src = instantiateVariableFont(src, {"wght": 400})

upm = src["head"].unitsPerEm
cap = src["OS/2"].sCapHeight
glyph_set = src.getGlyphSet()
reg = glyph_set[src.getBestCmap()[0xAE]]

# Bounds of the source glyph, to place the scaled copy.
bp = BoundsPen(glyph_set)
reg.draw(bp)
x0, y0, x1, y1 = bp.bounds

# Scale, then move so the left edge sits at GAP and the top meets cap height.
dx = GAP - x0 * SCALE
dy = cap - y1 * SCALE
pen = TTGlyphPen(None)
reg.draw(TransformPen(pen, (SCALE, 0, 0, SCALE, dx, dy)))
glyph = pen.glyph()
advance = round((x1 - x0) * SCALE + 2 * GAP)

ascent = src["hhea"].ascent
descent = src["hhea"].descent

fb = FontBuilder(upm, isTTF=True)
fb.setupGlyphOrder([".notdef", "registered"])
fb.setupCharacterMap({0xAE: "registered"})
fb.setupGlyf({".notdef": TTGlyphPen(None).glyph(), "registered": glyph})
fb.setupHorizontalMetrics({".notdef": (0, 0), "registered": (advance, GAP)})
fb.setupHorizontalHeader(ascent=ascent, descent=descent)
fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
fb.setupOS2(
    sTypoAscender=ascent, sTypoDescender=descent, usWinAscent=ascent,
    usWinDescent=-descent, sCapHeight=cap,
)
fb.setupPost()

buf = io.BytesIO()
fb.font.flavor = "woff2"
fb.font.save(buf)
b64 = base64.b64encode(buf.getvalue()).decode()

OUT.write_text(
    f"""// GENERATED by scripts/design/build-reg-mark-font.py — do not edit.
// A font with one glyph: Roboto's ® at {SCALE:g}× and lifted to cap height,
// so body copy prints ® as a superscript. Used via withRegMark() in
// typography.ts; see the script for why this is a font and not <sup>.

export const REG_MARK_FAMILY = "{FAMILY}";

/** Put inside each layout's <style>, after the @import lines. */
export const REG_MARK_FONT_FACE = `@font-face {{
  font-family: '{FAMILY}';
  src: url(data:font/woff2;base64,{b64}) format('woff2');
  unicode-range: U+00AE;
  font-weight: 100 900;
  font-style: normal;
}}`;
"""
)
print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({len(buf.getvalue())} bytes woff2)")
